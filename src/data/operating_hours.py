"""Эксплуатационные часы метро для пассажирского потока.

Метро принимает пассажиров по расписанию: входы начинаются в 05:30 и заканчиваются около 00:30.
Все остальное время (00:30-05:15) в турникетных данных - это проходы сотрудников (смены, технологические
окна), а не пассажиры. Эти записи не входят в пассажиропоток, поэтому вырезаются.

Подтверждение по данным (4 месяца, 24 вестибюля, 15-минутный шаг):
  - 05:15 -> 12 055 входов, 05:30 -> 332 565 (рывок в 27 раз): начало пассажирской работы.
  - 04:30 -> 15 630 (всплеск смены сотрудников на нескольких станциях), 04:00-05:15 в сумме ~21 тыс.
  - 00:15 -> 44 319, 00:30 -> 6 124, 01:00 -> 2 293: закрытие станций на вход.
Удаляется 57 600 строк (20.8%), в них 50 376 проходов (0.066% потока).
"""
import pandas as pd

OPEN_MIN = 5 * 60 + 30   # 05:30 - первый пассажирский слот
CLOSE_MIN = 30           # 00:30 - первый слот после закрытия (слот 00:15 еще пассажирский)


def operating_mask(dt: pd.Series) -> pd.Series:
    """True для 15-минутных слотов, в которых метро работает на пассажиров."""
    dt = pd.to_datetime(dt)
    minute_of_day = dt.dt.hour * 60 + dt.dt.minute
    return (minute_of_day >= OPEN_MIN) | (minute_of_day < CLOSE_MIN)


def filter_operating_hours(df: pd.DataFrame, dt_col: str = "datetime", verbose: bool = False) -> pd.DataFrame:
    """Оставляет только пассажирские слоты 05:30-00:30. Остальное - сотрудники/технологическое окно."""
    mask = operating_mask(df[dt_col])
    if verbose:
        removed = df.loc[~mask]
        pax = removed["passengers"].sum() if "passengers" in removed else float("nan")
        print(f"operating_hours: удалено {len(removed)} строк ({(~mask).mean():.1%}), проходов сотрудников: {pax:,.0f}")
    return df.loc[mask].reset_index(drop=True)
